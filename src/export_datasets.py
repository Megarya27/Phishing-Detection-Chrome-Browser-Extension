#This program outputs the preprocessed datasets and a summary of their 
# statistics to the prepared_datasets directory. 
import json
import pandas as pd
from global_config import ( ROOT, STRUCTURAL_FEATURES, ADVERSARIAL_DIR, RANDOM_SEED)
from data_structural import load_structural_splits
from data_text import build_text_dataset

PREPARED_DIR = ROOT / "prepared_datasets"
STRUCTURAL_OUT = PREPARED_DIR / "structural"
TEXT_OUT = PREPARED_DIR / "text"
#create output directories if they dont exist yet
STRUCTURAL_OUT.mkdir(parents=True, exist_ok=True)
TEXT_OUT.mkdir(parents=True, exist_ok=True)

# loads UCI Phishing Websites dataset, splits into train,validation, and test, 
# and exports each split to CSV files in the prepared_datasets/structural directory. 
# Also returns a dictionary of statistics about each split.
def export_structural():
    # load dictionary containing data splits 
    splits = load_structural_splits()
    stats = {}
    # iterate through splits
    for split_name in ["train", "val", "test"]:
        #extract features (X) and target labels (y)
        features_df = splits[f"X_{split_name}"]
        labels_series = splits[f"y_{split_name}"]
        combined_df = features_df.copy() # make separate copy for avoiding modifying original data
        combined_df["label"] = labels_series.values # add target label column to the dataFrame
        #save to CSV, index=False because row numbers not needed
        csv_destination = STRUCTURAL_OUT / f"{split_name}.csv"
        combined_df.to_csv(csv_destination, index=False)

        # calculate counts for class balance
        total_samples = len(combined_df)
        phishing_count = int((labels_series == 1).sum())
        legitimate_count = int((labels_series == 0).sum())
        phishing_ratio = float(phishing_count / total_samples) if total_samples > 0 else 0.0

        #store calculated metrics for this split
        stats[split_name] = {
            "n_samples": total_samples,
            "n_features": len(STRUCTURAL_FEATURES),
            "phishing_count": phishing_count,
            "legitimate_count": legitimate_count,
            "phishing_ratio": phishing_ratio}
    return stats

# exports text dataset splits to CSV files and calculates statistics for each split.
def export_text():
    #load dictionary of text dataFrames
    splits = build_text_dataset()
    stats = {}

    for split_name, df in splits.items():
        #save DataFrame to csv
        csv_destination = TEXT_OUT / f"{split_name}.csv"
        df.to_csv(csv_destination, index=False)

        #calculate word count per text sample
        word_lists = df["text"].str.split()
        token_lengths = word_lists.str.len()

        #calculate class distribution
        total_samples = len(df)
        phishing_count = int((df["label"] == 1).sum())
        legitimate_count = int((df["label"] == 0).sum())
        phishing_ratio = float(phishing_count / total_samples) if total_samples > 0 else 0.0
        source_counts = df["source"].value_counts().to_dict() #breakdown of samples by original data source
        # record metrics
        stats[split_name] = {
            "n_samples": total_samples,
            "phishing_count": phishing_count,
            "legitimate_count": legitimate_count,
            "phishing_ratio": phishing_ratio,
            "source_breakdown": source_counts,
            "mean_tokens_per_sample": float(token_lengths.mean()),
            "median_tokens_per_sample": float(token_lengths.median()),
            "max_tokens_per_sample": int(token_lengths.max()),
        }

    return stats

#summarises adversarial evaluation set, generated by a different script (src\adversarial_dataset_generation.py).
def summarise_adversarial():
    stats = {}
    #map technique names to expected CSV filenames for differntiating between structural and semantic adversarial techniques
    structural_files = {
        "ssl_certificate_injection": "adv_ssl_certificate_injection.csv",
        "domain_reputation_laundering": "adv_domain_reputation_laundering.csv",
        "lexical_feature_normalisation": "adv_lexical_feature_normalisation.csv",
    }

    #check structural adversarial files
    for technique_name, filename in structural_files.items():
        file_path = ADVERSARIAL_DIR / filename
        
        if file_path.exists():
            df = pd.read_csv(file_path)
            stats[technique_name] = {
                "n_samples": int(len(df)),
                "modality": "structural",
            }
        else:
            stats[technique_name] = {
                "n_samples": 0,
                "modality": "structural",
                "status": "NOT GENERATED",
            }

    # check semantic adversarial files
    semantic_file_path = ADVERSARIAL_DIR / "adv_semantic_obfuscation.csv"
    
    if semantic_file_path.exists():
        df_semantic = pd.read_csv(semantic_file_path)
        
        # calculate token/word counts for obfuscated text
        word_lists = df_semantic["obfuscated_text"].str.split()
        token_lengths = word_lists.str.len()

        stats["semantic_obfuscation"] = {
            "n_samples": int(len(df_semantic)),
            "modality": "semantic",
            "mean_tokens_per_sample": float(token_lengths.mean())}
    else:
        stats["semantic_obfuscation"] = {
            "n_samples": 0,
            "modality": "semantic",
            "status": "NOT GENERATED"}

    # calculate total adversarial samples across all techniques
    total_samples = 0
    for technique_data in stats.values():
        total_samples += technique_data.get("n_samples", 0)
    stats["total_adversarial_samples"] = total_samples
    return stats

def main():
    print("Exporting preprocessed structural benchmark dataset...")
    structural_stats = export_structural()

    print("Exporting finalised NLP training corpus...")
    text_stats = export_text()

    print("Summarising adversarial evaluation set (run the generator script first if missing)...")
    adversarial_stats = summarise_adversarial()

    all_stats = {
        "random_seed": RANDOM_SEED,
        "structural_benchmark_dataset": structural_stats,
        "nlp_training_corpus": text_stats,
        "adversarial_evaluation_set": adversarial_stats,
    }
    out_path = PREPARED_DIR / "dataset_statistics.json"
    with open(out_path, "w") as f:
        json.dump(all_stats, f, indent=2)
    print(f"Wrote statistics summary to {out_path}")


if __name__ == "__main__":
    main()
